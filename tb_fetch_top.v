`timescale 1ns/1ps

module tb_fetch_top;

    reg         clk;
    reg         rst_n;
    reg  [31:0] next_pc;

    wire [31:0] pc;
    wire [31:0] pc_plus4;
    wire [31:0] instruction;


    // -----------------------------------------
    // Fetch Top
    // -----------------------------------------

    fetch_top uut (

        .clk         (clk),
        .rst_n       (rst_n),
        .next_pc     (next_pc),

        .pc          (pc),
        .pc_plus4    (pc_plus4),
        .instruction (instruction)

    );


    // -----------------------------------------
    // Clock
    // -----------------------------------------

    always #5 clk = ~clk;


    // -----------------------------------------
    // Test sequence
    // -----------------------------------------

    initial begin

        clk = 1'b0;
        rst_n = 1'b0;
        next_pc = 32'd0;

        #10;

        // Release reset
        rst_n = 1'b1;

        // -------------------------------------
        // Fetch address 0
        // -------------------------------------

        next_pc = 32'd0;

        #10;


        // -------------------------------------
        // Fetch address 4
        // -------------------------------------

        next_pc = 32'd4;

        #10;


        // -------------------------------------
        // Fetch address 8
        // -------------------------------------

        next_pc = 32'd8;

        #10;


        // -------------------------------------
        // Fetch address 12
        // -------------------------------------

        next_pc = 32'd12;

        #10;


        // -------------------------------------
        // Fetch address 16
        // -------------------------------------

        next_pc = 32'd16;

        #10;


        $stop;

    end

endmodule